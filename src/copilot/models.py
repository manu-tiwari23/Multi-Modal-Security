"""
Pydantic data models for the AI Security Copilot module.

Includes query specifications, citations, tool call execution records,
containment recommendations, conversation history, and incident report schemas.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Literal, Optional
from uuid import uuid4

from pydantic import BaseModel, Field, ConfigDict


# ---------------------------------------------------------------------------
# Citation & Evidence Grounding Models
# ---------------------------------------------------------------------------

CitationType = Literal["event", "incident", "alert", "ioc", "honeypot", "rule"]


class Citation(BaseModel):
    """An explicit citation linking an AI claim back to ground-truth evidence."""

    id: str
    type: CitationType
    title: str
    snippet: str = ""
    timestamp: Optional[datetime] = None
    source: Optional[str] = None
    metadata: dict[str, Any] = Field(default_factory=dict)


# ---------------------------------------------------------------------------
# Tool Execution Records
# ---------------------------------------------------------------------------


class ToolCallRecord(BaseModel):
    """Record of an individual tool called during Copilot reasoning."""

    tool_name: str
    arguments: dict[str, Any] = Field(default_factory=dict)
    result_summary: str = ""
    success: bool = True
    error_message: Optional[str] = None
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    retrieved_ids: list[str] = Field(default_factory=list)
    result_sha256: Optional[str] = None
    limitations: list[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Containment & Response Recommendations (Human-in-the-loop)
# ---------------------------------------------------------------------------


class ContainmentRecommendation(BaseModel):
    """Recommended containment action. Always requires human analyst sign-off."""

    action_type: str  # e.g. "block_ip", "isolate_host", "revoke_credentials", "quarantine_file"
    target: str       # e.g. "203.0.113.88", "prod-web-01", "root"
    rationale: str
    requires_approval: Literal[True] = True
    priority: Literal["low", "medium", "high", "critical"] = "high"


# ---------------------------------------------------------------------------
# Conversational Messages & Queries
# ---------------------------------------------------------------------------


class ChatMessage(BaseModel):
    """Single message in a multi-turn Copilot conversation."""

    model_config = ConfigDict(extra="forbid")
    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=4000)


class CopilotQuery(BaseModel):
    """Input payload for a Copilot interaction."""

    model_config = ConfigDict(extra="forbid")
    prompt: str = Field(min_length=1, max_length=4000, pattern=r"\S")
    session_id: Optional[str] = Field(default=None, max_length=128)
    incident_id: Optional[str] = Field(default=None, min_length=1, max_length=128)
    history: list[ChatMessage] = Field(default_factory=list, max_length=12)
    mode: Literal["auto", "local"] = "auto"


class CopilotResponse(BaseModel):
    """Complete response from the AI Copilot with citations and recommendations."""

    query: str
    answer: str
    citations: list[Citation] = Field(default_factory=list)
    tool_calls: list[ToolCallRecord] = Field(default_factory=list)
    recommendations: list[ContainmentRecommendation] = Field(default_factory=list)
    model: str = "mms-copilot-gpt4"
    execution_time_ms: float = 0.0
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    audit_id: str = Field(default_factory=lambda: str(uuid4()))
    limitations: list[str] = Field(default_factory=list)
    usage: dict[str, int] = Field(default_factory=dict)


# ---------------------------------------------------------------------------
# Structured Incident Report
# ---------------------------------------------------------------------------


class IncidentReport(BaseModel):
    """Comprehensive forensic and incident response report generated by Copilot."""

    report_id: str = Field(default_factory=lambda: f"REP-{uuid4().hex[:8].upper()}")
    incident_id: str
    title: str
    risk_score: float
    priority: str
    executive_summary: str
    technical_analysis: str
    attack_timeline: list[dict[str, Any]] = Field(default_factory=list)
    iocs: list[dict[str, Any]] = Field(default_factory=list)
    mitre_matrix: list[dict[str, Any]] = Field(default_factory=list)
    containment_actions: list[ContainmentRecommendation] = Field(default_factory=list)
    analyst_notes: str = ""
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    def to_markdown(self) -> str:
        """Render the complete structured report to analyst-ready Markdown."""
        lines = [
            f"# 🛡️ MMS Incident & Forensic Report: {self.title}",
            f"**Report ID:** `{self.report_id}` | **Incident ID:** `{self.incident_id}`",
            f"**Risk Score:** `{self.risk_score:.1f}/100.0` | **Priority:** `{self.priority}`",
            f"**Generated:** `{self.created_at.strftime('%Y-%m-%d %H:%M:%S UTC')}`",
            "",
            "---",
            "",
            "## 1. Executive Summary",
            self.executive_summary,
            "",
            "## 2. Technical Attack Analysis",
            self.technical_analysis,
            "",
            "## 3. Chronological Attack Timeline",
        ]

        if self.attack_timeline:
            for item in self.attack_timeline:
                ts = item.get("timestamp", "N/A")
                source = item.get("source", "unknown")
                desc = item.get("description", "")
                sev = item.get("severity", "low")
                lines.append(f"- **`{ts}`** `[{source.upper()}]` `({sev.upper()})` — {desc}")
        else:
            lines.append("_No timeline events recorded._")

        lines.extend([
            "",
            "## 4. Indicators of Compromise (IOCs)",
            "| Type | Value | Context |",
            "|---|---|---|",
        ])

        if self.iocs:
            for ioc in self.iocs:
                lines.append(f"| {ioc.get('type', 'N/A')} | `{ioc.get('value', 'N/A')}` | {ioc.get('context', 'Observed in attack')} |")
        else:
            lines.append("| None | — | No specific IOCs extracted |")

        lines.extend([
            "",
            "## 5. MITRE ATT&CK Matrix Mapping",
            "| Technique ID | Name / Tactic | Detection Source |",
            "|---|---|---|",
        ])

        if self.mitre_matrix:
            for m in self.mitre_matrix:
                lines.append(f"| `{m.get('id', 'N/A')}` | {m.get('name', 'N/A')} | {m.get('source', 'SOC Rule')} |")
        else:
            lines.append("| None | — | — |")

        lines.extend([
            "",
            "## 6. Recommended Containment & Remediation (Requires Analyst Sign-off)",
        ])

        if self.containment_actions:
            for i, act in enumerate(self.containment_actions, 1):
                lines.append(
                    f"{i}. **Action:** `{act.action_type.upper()}` on `{act.target}` ({act.priority} priority)\n"
                    f"   - **Rationale:** {act.rationale}\n"
                    f"   - **Human Approval Status:** `[ ] Pending Analyst Authorization`"
                )
        else:
            lines.append("_No automated containment recommendations generated._")

        return "\n".join(lines)
